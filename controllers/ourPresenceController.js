function mergeDefaults(defaults, saved) {
  if (Array.isArray(defaults)) {
    return Array.isArray(saved) ? saved : defaults;
  }

  if (
    defaults &&
    typeof defaults === "object" &&
    !Array.isArray(defaults)
  ) {
    const result = { ...defaults };

    for (const key of Object.keys(defaults)) {
      result[key] = mergeDefaults(defaults[key], saved?.[key]);
    }

    return result;
  }

  return saved ?? defaults;
}

export async function getOurPresence(req, res) {
  try {
    const page = await OurPresencePage.findOne({
      key: "our-presence",
    }).lean();

    const content = mergeDefaults(
      OUR_PRESENCE_DEFAULTS,
      page?.content || {}
    );

    if (!page?.published || !content.isPublished) {
      return res.status(404).json({
        success: false,
        message: "Our Presence page is not available.",
      });
    }

    return res.json({
      success: true,
      data: content,
    });
  } catch (error) {
    console.error("Get Our Presence:", error);

    return res.status(500).json({
      success: false,
      message: "Unable to load Our Presence page.",
    });
  }
}

export async function getOurPresenceAdmin(req, res) {
  try {
    let page = await OurPresencePage.findOne({
      key: "our-presence",
    });

    if (!page) {
      page = await OurPresencePage.create({
        key: "our-presence",
        content: OUR_PRESENCE_DEFAULTS,
        published: true,
        updatedBy: req.admin?._id || null,
      });
    }

    return res.json({
      success: true,
      data: mergeDefaults(
        OUR_PRESENCE_DEFAULTS,
        page.content || {}
      ),
      published: page.published,
    });
  } catch (error) {
    console.error("Get Our Presence Admin:", error);

    return res.status(500).json({
      success: false,
      message: "Unable to load Our Presence content.",
    });
  }
}

export async function updateOurPresence(req, res) {
  try {
    const content = req.body?.content || req.body;

    if (
      !content ||
      typeof content !== "object" ||
      Array.isArray(content)
    ) {
      return res.status(400).json({
        success: false,
        message: "Invalid page content.",
      });
    }

    const mergedContent = mergeDefaults(
      OUR_PRESENCE_DEFAULTS,
      content
    );

    const published = Boolean(mergedContent.isPublished);

    const page = await OurPresencePage.findOneAndUpdate(
      { key: "our-presence" },
      {
        $set: {
          content: mergedContent,
          published,
          updatedBy: req.admin?._id || null,
        },
      },
      {
        new: true,
        upsert: true,
        runValidators: true,
        setDefaultsOnInsert: true,
      }
    );

    return res.json({
      success: true,
      message: "Our Presence page updated successfully.",
      data: page.content,
      published: page.published,
    });
  } catch (error) {
    console.error("Update Our Presence:", error);

    return res.status(500).json({
      success: false,
      message: "Unable to update Our Presence page.",
    });
  }
}
